//! Float ALU computes: fadd, fsub, fneg, float, trunc.
//!
//! The interpreter evaluates these in binary64 and rounds once to binary32,
//! which for add, subtract and multiply equals the binary32 operation. The
//! fast path implements only finite results; a NaN or an infinity (which the
//! interpreter reports through AV or AI and the sticky bits) exits before the
//! instruction. The device reads a denormal operand as a zero and returns a
//! denormal result as a zero (`floats.py`, "Denormal flush"): an operand that
//! is a nonzero denormal leaves (`rd_f_op`), and the sum or difference of
//! two other operands is exact, so a denormal result is replaced by the zero
//! of its sign (`flush_denormal_result`). Flags: AZ and AN from the result bit
//! pattern, AC AV AS AI cleared, AF set (`flags.py _float_alu_updates`).

use super::*;
use crate::fast::FlagKind;

/// The 8-bit seeds of `RECIPS` and `RSQRTS`, generated by `build.rs` from the
/// core's `seed_tables.py`.
mod seeds {
    include!(concat!(env!("OUT_DIR"), "/seed_tables.rs"));
}

/// Whether BASE is the host address of a seed table (a kernel load that is
/// not a window access: the window check of the reference interpreter skips it).
pub fn is_seed_table(base: u64) -> bool {
    [&seeds::RECIPS_SEED, &seeds::RSQRTS_SEED]
        .iter()
        .any(|t| t.as_ptr() as u64 == base)
}

impl Lower {
    /// RN = FX op FY (floats), the result checked to be in the fast domain.
    pub fn falu_binary(&mut self, b: Bin, rn: u32, rx: u32, ry: u32) -> LR<()> {
        let x = self.rd_f_op(rx)?;
        let y = self.rd_f_op(ry)?;
        let r = self.bin(b, x, y);
        // A denormal result (the operands are not denormal, so the sum is exact
        // and nonzero) is a flushed underflow: the interpreter latches the
        // sticky AUS for it (finding 103), so the kernel leaves before it.
        let rb = self.to_i(r);
        let m = self.ci(0x7fff_ffff);
        let mag = self.bin(Bin::And, rb, m);
        let one = self.ci(1);
        let m1 = self.bin(Bin::Sub, mag, one);
        let lim = self.ci(0x007f_ffff);
        let not_tiny = self.bin(Bin::GeU, m1, lim);
        self.guard(not_tiny);
        if self.cond.is_none() {
            self.ftz_ok.insert(r);
        }
        self.float_result(rn, r)
    }

    pub fn falu_neg(&mut self, rn: u32, rx: u32) -> LR<()> {
        let x = self.rd_f_op(rx)?;
        let r = self.un(Un::FNeg, x);
        self.float_result(rn, r)
    }

    /// Guard the f32 result R, write it to RN and note the Falu flags.
    pub fn float_result(&mut self, rn: u32, r: Val) -> LR<()> {
        result_finite(self, r);
        self.wr_f(rn, r)?;
        self.pend_flag(FlagKind::Falu, vec![r]);
        Ok(())
    }

    /// RN = float RX (int32 to float32, always in range).
    pub fn falu_float(&mut self, rn: u32, rx: u32) -> LR<()> {
        let x = self.rd_i(rx)?;
        let r = self.un(Un::IToF, x);
        self.wr_f(rn, r)?;
        self.pend_flag(FlagKind::Falu, vec![r]);
        Ok(())
    }

    /// RN = trunc FX: toward zero, only for |x| < 2^31.
    pub fn falu_trunc(&mut self, rn: u32, rx: u32) -> LR<()> {
        let x = self.rd_f(rx)?;
        let xb = self.to_i(x);
        let m = self.ci(0x7fff_ffff);
        let a = self.bin(Bin::And, xb, m);
        let lim = self.ci(0x4f00_0000);
        let ok = self.bin(Bin::LtU, a, lim);
        self.guard(ok);
        let r = self.un(Un::FToI, x);
        self.wr_i(rn, r)?;
        self.pend_flag(FlagKind::Falu, vec![r]);
        Ok(())
    }

    /// The f32 operand X is not a NaN (NaN returns all ones and sets AI).
    fn guard_not_nan(&mut self, x: Val) {
        let ok = self.bin(Bin::FEq, x, x);
        self.guard(ok);
    }

    /// RN = abs FX; AS carries the input's sign, AN is always clear.
    pub fn falu_abs(&mut self, rn: u32, rx: u32) -> LR<()> {
        let x = self.rd_f_op(rx)?;
        self.guard_not_nan(x);
        let r = self.un(Un::FAbs, x);
        self.wr_f(rn, r)?;
        self.pend_flag(FlagKind::Fabs, vec![r, x]);
        Ok(())
    }

    /// RN = pass FX (finite inputs).
    pub fn falu_pass(&mut self, rn: u32, rx: u32) -> LR<()> {
        let x = self.rd_f_op(rx)?;
        self.float_result(rn, x)
    }

    /// RN = clip FX by FY: FX if |FX| < |FY|, else FY's magnitude with FX's
    /// sign. A NaN operand and an infinite result exit.
    pub fn falu_clip(&mut self, rn: u32, rx: u32, ry: u32) -> LR<()> {
        let a = self.rd_f_op(rx)?;
        let b = self.rd_f_op(ry)?;
        self.guard_not_nan(a);
        self.guard_not_nan(b);
        let aa = self.un(Un::FAbs, a);
        let ab = self.un(Un::FAbs, b);
        let lt = self.bin(Bin::FLt, aa, ab);
        let abits = self.to_i(a);
        let bbits = self.to_i(b);
        let m = self.ci(0x7fff_ffff);
        let sg = self.ci(0x8000_0000);
        let mag = self.bin(Bin::And, bbits, m);
        let sign = self.bin(Bin::And, abits, sg);
        let clipped = self.bin(Bin::Or, mag, sign);
        let rbits = self.select(lt, abits, clipped);
        let r = self.to_f(rbits);
        self.float_result(rn, r)
    }

    /// RN = fmax / fmin (FX, FY) (`floats._float_max` / `_float_min`): FX
    /// when it is strictly larger (smaller) than FY, else FY; two zeros give
    /// -0 for min if either is negative and +0 for max if either is positive. The operands are bit
    /// patterns the core compares as binary64, which orders every f32 value
    /// (infinities included) as the f32 compare does; the
    /// result is one of the operands or the signed zero, so it needs no
    /// finite check. A NaN or denormal operand exits.
    pub fn falu_minmax(&mut self, rn: u32, rx: u32, ry: u32, max: bool) -> LR<()> {
        let a = self.rd_f_op(rx)?;
        let b = self.rd_f_op(ry)?;
        self.guard_not_nan(a);
        self.guard_not_nan(b);
        let pick_a = if max {
            self.bin(Bin::FLt, b, a)
        } else {
            self.bin(Bin::FLt, a, b)
        };
        let abits = self.to_i(a);
        let bbits = self.to_i(b);
        let both = self.bin(Bin::Or, abits, bbits);
        let m = self.ci(0x7fff_ffff);
        let mag = self.bin(Bin::And, both, m);
        let z = self.ci(0);
        let both_zero = self.bin(Bin::Eq, mag, z);
        let picked = self.select(pick_a, abits, bbits);
        // Two zeros: min is -0 if either is negative, max is +0 if either is
        // positive (the sign bits ORed, or ANDed, for the result's sign).
        let sg = self.ci(0x8000_0000);
        let sign_src = if max {
            self.bin(Bin::And, abits, bbits)
        } else {
            both
        };
        let zero = self.bin(Bin::And, sign_src, sg);
        let rbits = self.select(both_zero, zero, picked);
        let r = self.to_f(rbits);
        self.wr_f(rn, r)?;
        self.pend_flag(FlagKind::Falu, vec![r]);
        Ok(())
    }

    /// comp(FX, FY): flags only; a NaN or denormal operand exits.
    pub fn falu_compare(&mut self, rx: u32, ry: u32) -> LR<()> {
        let a = self.rd_f_op(rx)?;
        let b = self.rd_f_op(ry)?;
        self.guard_not_nan(a);
        self.guard_not_nan(b);
        let eq = self.bin(Bin::FEq, a, b);
        let lt = self.bin(Bin::FLt, a, b);
        let gt = self.bin(Bin::FLt, b, a);
        self.compare_flag(eq, lt, gt, true)
    }

    /// The biased exponent field of f32 bits XB.
    fn exp_field(&mut self, xb: Val) -> Val {
        let k23 = self.ci(23);
        let sh = self.bin(Bin::ShrU, xb, k23);
        let ff = self.ci(0xff);
        self.bin(Bin::And, sh, ff)
    }

    /// Guard that the shift amount SH (signed) is within +-1000, so that
    /// adding it to an exponent field cannot wrap.
    fn guard_shift_range(&mut self, sh: Val) {
        let k = self.ci(1000);
        let t = self.bin(Bin::Add, sh, k);
        let lim = self.ci(2000);
        let ok = self.bin(Bin::LtU, t, lim);
        self.guard(ok);
    }

    /// Guard that the f32 bits XB are zero or a normal number; returns the
    /// "is zero" truth value and the exponent field.
    fn guard_zero_or_normal(&mut self, xb: Val) -> (Val, Val) {
        let e = self.exp_field(xb);
        let m = self.ci(0x7fff_ffff);
        let mag = self.bin(Bin::And, xb, m);
        let z = self.ci(0);
        let iszero = self.bin(Bin::Eq, mag, z);
        let one = self.ci(1);
        let em1 = self.bin(Bin::Sub, e, one);
        let lim = self.ci(254);
        let normal = self.bin(Bin::LtU, em1, lim);
        self.guard_any(iszero, normal);
        (iszero, e)
    }

    /// F32 bits with the exponent field NE and the sign and mantissa of XB.
    fn with_exponent(&mut self, xb: Val, ne: Val) -> Val {
        let keep = self.ci(0x807f_ffff);
        let k23 = self.ci(23);
        let mant = self.bin(Bin::And, xb, keep);
        let exp = self.bin(Bin::Shl, ne, k23);
        self.bin(Bin::Or, mant, exp)
    }

    /// RN = logb FX for a finite normal FX: the unbiased exponent.
    pub fn falu_logb(&mut self, rn: u32, rx: u32) -> LR<()> {
        let x = self.rd_f(rx)?;
        let xb = self.to_i(x);
        let e = self.exp_field(xb);
        let one = self.ci(1);
        let em1 = self.bin(Bin::Sub, e, one);
        let lim = self.ci(254);
        let ok = self.bin(Bin::LtU, em1, lim);
        self.guard(ok);
        let bias = self.ci(127);
        let r = self.bin(Bin::Sub, e, bias);
        self.wr_i(rn, r)?;
        self.pend_flag(FlagKind::Falu, vec![r]);
        Ok(())
    }

    /// RN = mant FX: the hidden bit and fraction, left-justified. A NaN or an
    /// infinity leaves the kernel; exponent 0 (zero, denormal) gives 0 with a
    /// select, so the flags stay exact without leaving.
    pub fn falu_mant(&mut self, rn: u32, rx: u32) -> LR<()> {
        let x = self.rd_f(rx)?;
        let xb = self.to_i(x);
        let e = self.exp_field(xb);
        let k255 = self.ci(255);
        let ok = self.bin(Bin::LtU, e, k255);
        self.guard(ok);
        let fm = self.ci(0x7f_ffff);
        let frac = self.bin(Bin::And, xb, fm);
        let hid = self.ci(0x80_0000);
        let full = self.bin(Bin::Or, frac, hid);
        let k8 = self.ci(8);
        let shifted = self.bin(Bin::Shl, full, k8);
        let z = self.ci(0);
        let iszero = self.bin(Bin::Eq, e, z);
        let r = self.select(iszero, z, shifted);
        self.wr_i(rn, r)?;
        self.pend_flag(FlagKind::Fmant, vec![r, x]);
        Ok(())
    }

    /// RN = scalb FX by RY for FX zero or normal and no overflow; an
    /// underflow flushes to a signed zero.
    pub fn falu_scalb(&mut self, rn: u32, rx: u32, ry: u32) -> LR<()> {
        let x = self.rd_f(rx)?;
        let xb = self.to_i(x);
        let sh = self.rd_i(ry)?;
        self.guard_shift_range(sh);
        let (iszero, e) = self.guard_zero_or_normal(xb);
        let ne = self.bin(Bin::Add, e, sh);
        let k255 = self.ci(255);
        let notover = self.bin(Bin::LtS, ne, k255);
        self.guard_any(iszero, notover);
        let one = self.ci(1);
        let nem1 = self.bin(Bin::Sub, ne, one);
        let lim = self.ci(254);
        let inrange = self.bin(Bin::LtU, nem1, lim);
        let built = self.with_exponent(xb, ne);
        let sg = self.ci(0x8000_0000);
        let under = self.bin(Bin::And, xb, sg);
        let scaled = self.select(inrange, built, under);
        let bits = self.select(iszero, xb, scaled);
        let r = self.to_f(bits);
        self.wr_f(rn, r)?;
        self.pend_flag(FlagKind::Falu, vec![r]);
        Ok(())
    }

    /// RN = float RX by RY: exact for results with an exponent field of at
    /// least 2 (below that the rounding of the conversion decides the flush).
    pub fn falu_float_by(&mut self, rn: u32, rx: u32, ry: u32) -> LR<()> {
        let x = self.rd_i(rx)?;
        let sh = self.rd_i(ry)?;
        self.guard_shift_range(sh);
        let f = self.un(Un::IToF, x);
        let fb = self.to_i(f);
        let e = self.exp_field(fb);
        let m = self.ci(0x7fff_ffff);
        let mag = self.bin(Bin::And, fb, m);
        let z = self.ci(0);
        let iszero = self.bin(Bin::Eq, mag, z);
        let ne = self.bin(Bin::Add, e, sh);
        let two = self.ci(2);
        let nem2 = self.bin(Bin::Sub, ne, two);
        let lim = self.ci(253);
        let inrange = self.bin(Bin::LtU, nem2, lim);
        self.guard_any(iszero, inrange);
        let built = self.with_exponent(fb, ne);
        let bits = self.select(iszero, fb, built);
        let r = self.to_f(bits);
        self.wr_f(rn, r)?;
        self.pend_flag(FlagKind::Falu, vec![r]);
        Ok(())
    }

    /// RN = fix / trunc FX [by RY]. FX must be zero or normal and the scaled
    /// value below 2^31 in magnitude. `trunc` rounds toward zero; `fix`
    /// rounds to nearest, or toward zero when MODE1.TRUNCATE is set.
    pub fn falu_fix(&mut self, rn: u32, rx: u32, by: Option<u32>, trunc: bool) -> LR<()> {
        // `fix` follows MODE1.TRUNCATE (`floats._float_to_fixed`): the bit is
        // a translation-time constant, MODE1 as the kernel has it here
        // (`mode1_cur`: a MODE1 write earlier in the region counts); the
        // entry value is required at entry (`finish`, and in full after any
        // MODE1 write).
        let truncate = trunc || self.mode1_cur & (1 << 15) != 0;
        let x = self.rd_f(rx)?;
        let xb = self.to_i(x);
        let sh = match by {
            Some(ry) => {
                let sh = self.rd_i(ry)?;
                self.guard_shift_range(sh);
                sh
            }
            None => self.ci(0),
        };
        let (iszero, e) = self.guard_zero_or_normal(xb);
        let ne = self.bin(Bin::Add, e, sh);
        let k158 = self.ci(158);
        let small = self.bin(Bin::LtS, ne, k158);
        self.guard_any(iszero, small);
        let one = self.ci(1);
        let under = self.bin(Bin::LtS, ne, one);
        let zero_res = self.bin(Bin::Or, iszero, under);
        let built = self.with_exponent(xb, ne);
        let sf = self.to_f(built);
        let rounded = if truncate {
            sf
        } else {
            // Round to nearest even below 2^23 by adding and subtracting
            // 2^23 with the sign of the value; larger values are integers.
            let c = self.cf(0x4b00_0000);
            let nc = self.cf(0xcb00_0000);
            let k31 = self.ci(31);
            let neg = self.bin(Bin::ShrU, built, k31);
            let mg = self.select(neg, nc, c);
            let a = self.bin(Bin::FAdd, sf, mg);
            let r = self.bin(Bin::FSub, a, mg);
            let abs = self.un(Un::FAbs, sf);
            let isn = self.bin(Bin::FLt, abs, c);
            self.select(isn, r, sf)
        };
        let i = self.un(Un::FToI, rounded);
        let z = self.ci(0);
        let r = self.select(zero_res, z, i);
        if !trunc {
            // FIX of a nonzero scaled value that returns zero latches the
            // sticky AUS in the interpreter (finding 103): leave the kernel.
            let nonzero = self.bin(Bin::Ne, r, z);
            self.guard_any(zero_res, nonzero);
        }
        self.wr_i(rn, r)?;
        self.pend_flag(FlagKind::Falu, vec![r]);
        Ok(())
    }

    /// `TABLE[idx]` (idx in 0..128, a byte table of the build): a load at the
    /// table's host address. The kernel holds that address, as a helper call
    /// holds its record.
    fn seed_load(&mut self, table: &'static [u8; 128], idx: Val) -> Val {
        let base = self.emit(Ty::I64, Op::CI64(table.as_ptr() as u64));
        self.emit(
            Ty::I32,
            Op::LoadN {
                base,
                off: idx,
                bytes: 1,
            },
        )
    }

    /// The f32 with the sign, exponent field `exp` and the 8-bit seed `seed`
    /// as its top mantissa bits (the low 15 bits are zero).
    fn seed_result(&mut self, sign: Val, exp: Val, seed: Val) -> Val {
        let k23 = self.ci(23);
        let k15 = self.ci(15);
        let e = self.bin(Bin::Shl, exp, k23);
        let m = self.bin(Bin::Shl, seed, k15);
        let r = self.bin(Bin::Or, e, m);
        let r = self.bin(Bin::Or, r, sign);
        self.to_f(r)
    }

    /// RN = recips FX for an exponent field of 1..=252: sign of the input,
    /// biased exponent 253 - e, mantissa `RECIPS_SEED[m >> 16]`. The result
    /// is nonzero with the input's sign, so AZ, AN and AF are those of
    /// `FlagKind::Falu`; AI, AV, AC and AS are clear and no sticky bit
    /// latches (the other inputs leave the kernel).
    pub fn falu_recips(&mut self, rn: u32, rx: u32) -> LR<()> {
        let x = self.rd_f(rx)?;
        let xb = self.to_i(x);
        let e = self.exp_field(xb);
        let one = self.ci(1);
        let em1 = self.bin(Bin::Sub, e, one);
        let lim = self.ci(252);
        let ok = self.bin(Bin::LtU, em1, lim);
        self.guard(ok);
        let k16 = self.ci(16);
        let m = self.bin(Bin::ShrU, xb, k16);
        let k7f = self.ci(0x7f);
        let idx = self.bin(Bin::And, m, k7f);
        let seed = self.seed_load(&seeds::RECIPS_SEED, idx);
        let c253 = self.ci(253);
        let ne = self.bin(Bin::Sub, c253, e);
        let sm = self.ci(0x8000_0000);
        let sign = self.bin(Bin::And, xb, sm);
        let r = self.seed_result(sign, ne, seed);
        self.wr_f(rn, r)?;
        self.pend_flag(FlagKind::Falu, vec![r]);
        Ok(())
    }

    /// RN = rsqrts FX for a positive input with an exponent field of
    /// 1..=254: biased exponent 126 - ((e - 127) >> 1), mantissa
    /// `RSQRTS_SEED[(e & 1) << 6 | m >> 17]`, positive. The result is
    /// nonzero and positive: AF only, as `FlagKind::Falu`.
    pub fn falu_rsqrts(&mut self, rn: u32, rx: u32) -> LR<()> {
        let x = self.rd_f(rx)?;
        let xb = self.to_i(x);
        let lo = self.ci(0x0080_0000);
        let off = self.bin(Bin::Sub, xb, lo);
        let lim = self.ci(0x7f00_0000);
        let ok = self.bin(Bin::LtU, off, lim);
        self.guard(ok);
        let e = self.exp_field(xb);
        let k1 = self.ci(1);
        let odd = self.bin(Bin::And, e, k1);
        let k6 = self.ci(6);
        let hi = self.bin(Bin::Shl, odd, k6);
        let k17 = self.ci(17);
        let m = self.bin(Bin::ShrU, xb, k17);
        let k3f = self.ci(0x3f);
        let m6 = self.bin(Bin::And, m, k3f);
        let idx = self.bin(Bin::Or, hi, m6);
        let seed = self.seed_load(&seeds::RSQRTS_SEED, idx);
        let c127 = self.ci(127);
        let unb = self.bin(Bin::Sub, e, c127);
        let half = self.bin(Bin::ShrS, unb, k1);
        let c126 = self.ci(126);
        let ne = self.bin(Bin::Sub, c126, half);
        let zero = self.ci(0);
        let r = self.seed_result(zero, ne, seed);
        self.wr_f(rn, r)?;
        self.pend_flag(FlagKind::Falu, vec![r]);
        Ok(())
    }
}
