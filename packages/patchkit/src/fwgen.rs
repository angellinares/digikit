//! The firmware declarations (`devices/fw/`): `patchkit gen` writes the bindings of the `core/*` adapters from them. They are a Rust
//! crate (`dkfw`), C headers and GAS include files under `modules/core/fw/`. Content modules never use them. Only ColdFire
//! (`cpu = "cf"`) entries make output; `gen --check` keeps the files current.

use crate::error::*;
use serde::Deserialize;
use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::Path;

/// The declaration directory, relative to the repository root.
pub const SOURCE: &str = "devices/fw";
/// The output directory, relative to the repository root.
pub const OUT_DIR: &str = "modules/core/fw";
/// The generated Rust crate source, relative to the repository root.
pub const RUST_OUT: &str = "modules/core/fw/rs/src/lib.rs";
/// Whether a `sig` may return a pointer. Allowed since the static check of 2026-10-27 [D]: our m68k-elf gcc and the Rust backend
/// read a returned pointer from d0, and operator new, `cf.view.fn.brain.instance` and `cf.view.fn.brain.view_manager` set d0 (DT2 1.17; operator new on
/// DN2 1.12 too).
pub const POINTER_RETURNS_ALLOWED: bool = true;

const HEADER: &str = "Generated by `patchkit gen` from devices/fw/. Do not edit.";
const SCALARS: [&str; 7] = ["u8", "u16", "u32", "i8", "i16", "i32", "bool"];

/// The tables of a declaration file.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Files {
    #[serde(default)]
    r#fn: Vec<Entry>,
    #[serde(default)]
    site: Vec<Entry>,
    #[serde(default)]
    data: Vec<Entry>,
    #[serde(default)]
    value: Vec<Entry>,
    #[serde(default)]
    sites: Vec<Entry>,
    // A hook with a `handler` makes a handler type and an assembly macro; any malformed hook fails `gen`.
    #[serde(default)]
    hook: Vec<Hook>,
    #[serde(default)]
    r#struct: Vec<StructEntry>,
}

/// A `fn`, `site`, `data`, `value` or `sites` entry. Only `name`, `cpu`, `sig` and `bind` are used here.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
#[allow(dead_code)]
struct Entry {
    name: String,
    #[serde(default)]
    was: Vec<String>,
    cpu: String,
    #[serde(default)]
    devices: Vec<String>,
    rule: toml::Value,
    mark: Option<String>,
    #[serde(default)]
    users: Vec<String>,
    sig: Option<String>,
    /// Only on a `site`: `"static"` emits the site as a static, like a `data` entry.
    bind: Option<String>,
    doc: Option<String>,
}

/// A `hook` entry: a point in a declared `site` where a handler can run. Only a ColdFire hook with a `handler` makes output.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
#[allow(dead_code)]
struct Hook {
    name: String,
    site: String,
    #[serde(default)]
    offset: u32,
    mode: String,
    regs: Regs,
    handler: Option<Handler>,
    #[serde(default)]
    was: Vec<String>,
    cpu: Option<String>,
    #[serde(default)]
    devices: Vec<String>,
    mark: Option<String>,
    #[serde(default)]
    users: Vec<String>,
    doc: Option<String>,
}

/// The registers of a hook: the ones the stub reads and the ones it may change. A SHARC hook can also name the mode state.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Regs {
    #[serde(default, rename = "in")]
    inputs: Vec<String>,
    #[serde(default)]
    clobbers: Vec<String>,
    #[serde(default)]
    modes: Option<toml::Table>,
}

/// The C function a ColdFire hook calls: its `sig` and where each argument comes from (`d0`-`d7`, `a0`-`a6` or `sp+N`).
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Handler {
    sig: String,
    args: Vec<String>,
}

/// A `struct` entry. A per-device difference is not supported yet, so any other key is an error.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
#[allow(dead_code)]
struct StructEntry {
    name: String,
    cpu: Option<String>,
    size: u32,
    fields: Vec<FieldEntry>,
    mark: Option<String>,
    #[serde(default)]
    users: Vec<String>,
    doc: Option<String>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct FieldEntry {
    name: String,
    off: u32,
    r#type: String,
}

/// A type of a `sig`: `const`, a base and the number of `*`.
struct Ty {
    is_const: bool,
    base: String,
    ptr: usize,
}

struct Sig {
    ret: Ty,
    args: Vec<(Ty, String)>,
    varargs: bool,
}

/// One slot of a struct layout.
enum Slot {
    Field { name: String, ty: String, off: u32 },
    Pad { idx: usize, len: u32 },
}

struct StructDef {
    name: String,
    short: String,
    size: u32,
    slots: Vec<Slot>,
    doc: String,
}

struct FnDef {
    name: String,
    rust: String,
    sig: Option<Sig>,
    doc: String,
}

struct StaticDef {
    name: String,
    rust: String,
    doc: String,
}

/// Where a handler argument comes from at the hook.
enum ArgSrc {
    Reg(String),
    /// `sp+N` at the hook, N a multiple of 4 and at least 4.
    Stack(u32),
}

/// A ColdFire hook with a `handler`.
struct HookDef {
    name: String,
    rust: String,
    doc: Option<String>,
    sig: Sig,
    /// The registers the macro saves around the call: d0, d1, a0, a1 without the `clobbers`.
    save: Vec<&'static str>,
    args: Vec<ArgSrc>,
}

#[derive(Default)]
struct Sub {
    structs: Vec<StructDef>,
    fns: Vec<FnDef>,
    statics: Vec<StaticDef>,
    hooks: Vec<HookDef>,
}

/// short name -> (subsystem, size) of every ColdFire struct.
type Info = BTreeMap<String, (String, u32)>;

/// The (subsystem, rust name) of a declaration name `<cpu>.<subsystem>.<kind>.<name>`, checking the kind.
fn split_name(name: &str, kind: &str) -> Result<(String, String)> {
    let p: Vec<&str> = name.split('.').collect();
    if p.len() < 4 || p[2] != kind || p[3..].iter().any(|s| s.is_empty()) {
        return Err(err!("{name}: expected <cpu>.<subsystem>.{kind}.<name>"));
    }
    Ok((p[1].to_string(), p[3..].join("_")))
}

/// Whether a `cpu` value selects ColdFire output.
fn is_cf(name: &str, cpu: &str) -> Result<bool> {
    match cpu {
        "cf" => Ok(true),
        "sharc" => Ok(false),
        _ => Err(err!("{name}: cpu {cpu:?} is not \"cf\" or \"sharc\"")),
    }
}

fn scalar_size(t: &str, info: &Info) -> Option<u32> {
    match t {
        "u8" | "i8" | "bool" => Some(1),
        "u16" | "i16" => Some(2),
        "u32" | "i32" | "ptr" => Some(4),
        _ => info.get(t).map(|(_, size)| *size),
    }
}

fn is_ident(s: &str) -> bool {
    !s.is_empty()
        && !s.starts_with(|c: char| c.is_ascii_digit())
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn tokens(s: &str) -> Vec<&str> {
    // `*` may touch the words around it
    let mut out = Vec::new();
    let mut start = None;
    for (i, c) in s.char_indices() {
        if c == '*' || c.is_whitespace() {
            if let Some(b) = start.take() {
                out.push(&s[b..i]);
            }
            if c == '*' {
                out.push(&s[i..i + 1]);
            }
        } else if start.is_none() {
            start = Some(i);
        }
    }
    if let Some(b) = start {
        out.push(&s[b..]);
    }
    out
}

/// A type from its tokens: `[const] <base> [*]...`.
fn parse_ty(name: &str, toks: &[&str], info: &Info) -> Result<Ty> {
    let (is_const, rest) = match toks.split_first() {
        Some((&"const", r)) => (true, r),
        _ => (false, toks),
    };
    let Some((base, stars)) = rest.split_first() else {
        return Err(err!("{name}: sig: a type is missing"));
    };
    if stars.iter().any(|s| *s != "*") {
        return Err(err!("{name}: sig: bad type {:?}", toks.join(" ")));
    }
    let ptr = stars.len();
    let known =
        SCALARS.contains(base) || *base == "void" || *base == "char" || info.contains_key(*base);
    if !known {
        return Err(err!("{name}: sig: unknown type {base:?}"));
    }
    if *base == "char" && ptr == 0 {
        return Err(err!("{name}: sig: char is only allowed behind a pointer"));
    }
    Ok(Ty {
        is_const,
        base: base.to_string(),
        ptr,
    })
}

/// `<ret> (<type> <name>, ..., ...)`.
fn parse_sig(name: &str, sig: &str, info: &Info) -> Result<Sig> {
    let sig = sig.trim();
    let open = sig
        .find('(')
        .ok_or_else(|| err!("{name}: sig {sig:?}: expected <ret> (<args>)"))?;
    if !sig.ends_with(')') {
        return Err(err!("{name}: sig {sig:?}: expected <ret> (<args>)"));
    }
    let ret = parse_ty(name, &tokens(&sig[..open]), info)?;
    if ret.ptr > 0 && !POINTER_RETURNS_ALLOWED {
        return Err(err!(
            "{name}: pointer return types wait for the d0/a0 check (plan step 5)"
        ));
    }
    let body = sig[open + 1..sig.len() - 1].trim();
    let mut args = Vec::new();
    let mut varargs = false;
    if !body.is_empty() {
        let parts: Vec<&str> = body.split(',').map(str::trim).collect();
        for (i, a) in parts.iter().enumerate() {
            if *a == "..." {
                if i + 1 != parts.len() {
                    return Err(err!("{name}: sig: `...` must be the last argument"));
                }
                varargs = true;
                continue;
            }
            let toks = tokens(a);
            let Some((arg, ty)) = toks.split_last() else {
                return Err(err!("{name}: sig: an argument is empty"));
            };
            if !is_ident(arg) || *arg == "const" {
                return Err(err!(
                    "{name}: sig: argument {a:?} needs a name after its type"
                ));
            }
            let ty = parse_ty(name, ty, info)?;
            if ty.base == "void" && ty.ptr == 0 {
                return Err(err!("{name}: sig: argument {arg} has type void"));
            }
            args.push((ty, arg.to_string()));
        }
    }
    Ok(Sig { ret, args, varargs })
}

/// The slots of a struct, in offset order with padding in the gaps and at the end.
fn layout(s: &StructEntry, info: &Info) -> Result<Vec<Slot>> {
    let mut fields: Vec<&FieldEntry> = s.fields.iter().collect();
    fields.sort_by_key(|f| f.off);
    let mut slots = Vec::new();
    let mut at: u64 = 0;
    let mut pads = 0;
    let mut pad = |slots: &mut Vec<Slot>, len: u64| {
        if len > 0 {
            slots.push(Slot::Pad {
                idx: pads,
                len: len as u32,
            });
            pads += 1;
        }
    };
    for (i, f) in fields.iter().enumerate() {
        if fields[..i].iter().any(|o| o.name == f.name) {
            return Err(err!("{}: field {} twice", s.name, f.name));
        }
        let size = scalar_size(&f.r#type, info)
            .ok_or_else(|| err!("{}: field {}: unknown type {:?}", s.name, f.name, f.r#type))?;
        let off = u64::from(f.off);
        if off < at {
            return Err(err!(
                "{}: field {} at {:#x} overlaps the field before it (ends at {at:#x})",
                s.name,
                f.name,
                f.off
            ));
        }
        let end = off + u64::from(size);
        if end > u64::from(s.size) {
            return Err(err!(
                "{}: field {} ends at {end:#x}, past size {:#x}",
                s.name,
                f.name,
                s.size
            ));
        }
        pad(&mut slots, off - at);
        slots.push(Slot::Field {
            name: f.name.clone(),
            ty: f.r#type.clone(),
            off: f.off,
        });
        at = end;
    }
    pad(&mut slots, u64::from(s.size) - at);
    Ok(slots)
}

/// Structs of one subsystem with the ones that others hold by value first (a C header needs the order).
fn order(sub: &str, structs: Vec<StructDef>, info: &Info) -> Result<Vec<StructDef>> {
    let mut left = structs;
    let mut out: Vec<StructDef> = Vec::new();
    while !left.is_empty() {
        let ready = left.iter().position(|s| {
            s.slots.iter().all(|sl| match sl {
                Slot::Field { ty, .. } => {
                    ty == &s.short
                        || info.get(ty).is_none_or(|(o, _)| o != sub)
                        || out.iter().any(|d| &d.short == ty)
                }
                Slot::Pad { .. } => true,
            })
        });
        match ready {
            Some(i) => out.push(left.remove(i)),
            None => return Err(err!("{}: structs hold each other by value", left[0].name)),
        }
    }
    Ok(out)
}

fn rs_scalar(t: &str) -> Option<&'static str> {
    Some(match t {
        "u8" => "u8",
        "u16" => "u16",
        "u32" => "u32",
        "i8" => "i8",
        "i16" => "i16",
        "i32" => "i32",
        "bool" => "bool",
        _ => return None,
    })
}

fn c_scalar(t: &str) -> Option<&'static str> {
    Some(match t {
        "u8" => "uint8_t",
        "u16" => "uint16_t",
        "u32" => "uint32_t",
        "i8" => "int8_t",
        "i16" => "int16_t",
        "i32" => "int32_t",
        "bool" => "bool",
        _ => return None,
    })
}

/// The Rust type of a struct field type or of a `sig` base.
fn rs_base(t: &str, info: &Info) -> String {
    if t == "ptr" {
        return "u32".into();
    }
    if t == "char" {
        return "u8".into();
    }
    if t == "void" {
        return "core::ffi::c_void".into();
    }
    match rs_scalar(t) {
        Some(s) => s.into(),
        None => format!("crate::{}::{t}", info[t].0),
    }
}

fn c_base(t: &str, info: &Info) -> String {
    if t == "ptr" {
        return "uint32_t".into();
    }
    if t == "char" || t == "void" || info.contains_key(t) {
        return t.into();
    }
    c_scalar(t).expect("a checked type").into()
}

fn rs_ty(t: &Ty, info: &Info) -> String {
    let mut s = rs_base(&t.base, info);
    for i in 0..t.ptr {
        s = format!(
            "*{} {s}",
            if i == 0 && t.is_const { "const" } else { "mut" }
        );
    }
    s
}

fn c_ty(t: &Ty, info: &Info) -> String {
    let mut s = String::new();
    if t.is_const {
        s.push_str("const ");
    }
    s.push_str(&c_base(&t.base, info));
    if t.ptr > 0 {
        s.push(' ');
        s.push_str(&"*".repeat(t.ptr));
    }
    s
}

fn c_decl(t: &Ty, name: &str, info: &Info) -> String {
    let ty = c_ty(t, info);
    if t.ptr > 0 {
        format!("{ty}{name}")
    } else {
        format!("{ty} {name}")
    }
}

fn rust_fn(f: &FnDef, sig: &Sig, info: &Info) -> String {
    let mut args: Vec<String> = sig
        .args
        .iter()
        .map(|(t, n)| format!("{n}: {}", rs_ty(t, info)))
        .collect();
    if sig.varargs {
        args.push("...".into());
    }
    let ret = if sig.ret.base == "void" && sig.ret.ptr == 0 {
        String::new()
    } else {
        format!(" -> {}", rs_ty(&sig.ret, info))
    };
    format!(
        "    unsafe extern \"C\" {{\n        /// {}\n        #[link_name = \"{}\"]\n        pub fn {}({}){ret};\n    }}\n",
        f.doc,
        f.name,
        f.rust,
        args.join(", ")
    )
}

/// `rust` in CamelCase: `settings_list_tail` -> `SettingsListTail`.
fn camel(rust: &str) -> String {
    rust.split('_')
        .map(|p| {
            let mut c = p.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

/// A doc text that fits in a C comment.
fn c_comment(doc: &str) -> String {
    doc.replace("*/", "* /")
}

fn rust_hook(h: &HookDef, info: &Info) -> String {
    let args: Vec<String> = h
        .sig
        .args
        .iter()
        .map(|(t, n)| format!("{n}: {}", rs_ty(t, info)))
        .collect();
    let ret = if h.sig.ret.base == "void" && h.sig.ret.ptr == 0 {
        String::new()
    } else {
        format!(" -> {}", rs_ty(&h.sig.ret, info))
    };
    let mut o = String::new();
    if let Some(d) = &h.doc {
        let _ = writeln!(o, "    /// {d}");
    }
    let _ = writeln!(
        o,
        "    pub type {}Hook = unsafe extern \"C\" fn({}){ret};",
        camel(&h.rust),
        args.join(", ")
    );
    o
}

fn rust_struct(s: &StructDef, info: &Info) -> String {
    let mut o = format!(
        "    /// {}\n    #[repr(C)]\n    pub struct {} {{\n",
        s.doc, s.short
    );
    for sl in &s.slots {
        match sl {
            Slot::Field { name, ty, .. } => {
                let _ = writeln!(o, "        pub {name}: {},", rs_base(ty, info));
            }
            Slot::Pad { idx, len } => {
                let _ = writeln!(o, "        pub _pad{idx}: [u8; {len}],");
            }
        }
    }
    o.push_str("    }\n");
    let _ = writeln!(
        o,
        "    #[cfg(target_arch = \"m68k\")]\n    const _: () = {{"
    );
    let _ = writeln!(
        o,
        "        assert!(core::mem::size_of::<{}>() == {:#x});",
        s.short, s.size
    );
    for sl in &s.slots {
        if let Slot::Field { name, off, .. } = sl {
            let _ = writeln!(
                o,
                "        assert!(core::mem::offset_of!({}, {name}) == {off:#x});",
                s.short
            );
        }
    }
    o.push_str("    };\n");
    o
}

fn rust(subs: &BTreeMap<String, Sub>, info: &Info) -> String {
    let mut s = format!(
        "// {HEADER}\n\n#![no_std]\n#![allow(non_camel_case_types, non_snake_case, dead_code)]\n"
    );
    for (sub, d) in subs {
        let _ = writeln!(s, "\npub mod {sub} {{");
        let mut items: Vec<String> = Vec::new();
        for st in &d.structs {
            items.push(rust_struct(st, info));
        }
        for f in &d.fns {
            items.push(match &f.sig {
                Some(sig) => rust_fn(f, sig, info),
                None => format!("    // {}: no sig yet\n", f.name),
            });
        }
        for v in &d.statics {
            items.push(format!(
                "    unsafe extern \"C\" {{\n        /// {}\n        #[link_name = \"{}\"]\n        pub static {}: u8;\n    }}\n",
                v.doc,
                v.name,
                v.rust.to_uppercase()
            ));
        }
        for h in &d.hooks {
            items.push(rust_hook(h, info));
        }
        s.push_str(&items.join("\n"));
        s.push_str("}\n");
    }
    s
}

fn c_header(sub: &str, d: &Sub, info: &Info) -> String {
    let guard = format!("DK_FW_{}_H", sub.to_uppercase());
    let mut s = format!(
        "/* {HEADER} */\n#ifndef {guard}\n#define {guard}\n\n#include <stdint.h>\n#include <stdbool.h>\n#include <stddef.h>\n"
    );
    // the headers of the structs this one uses
    let mut need: Vec<&str> = Vec::new();
    let mut note = |t: &str| {
        if let Some((o, _)) = info.get(t)
            && o != sub
            && !need.contains(&o.as_str())
        {
            need.push(o.as_str());
        }
    };
    for st in &d.structs {
        for sl in &st.slots {
            if let Slot::Field { ty, .. } = sl {
                note(ty);
            }
        }
    }
    for f in &d.fns {
        if let Some(sig) = &f.sig {
            note(&sig.ret.base);
            for (t, _) in &sig.args {
                note(&t.base);
            }
        }
    }
    for h in &d.hooks {
        note(&h.sig.ret.base);
        for (t, _) in &h.sig.args {
            note(&t.base);
        }
    }
    need.sort();
    for o in need {
        let _ = writeln!(s, "#include \"dk_fw_{o}.h\"");
    }
    for st in &d.structs {
        let _ = writeln!(s, "\n/* {} */", c_comment(&st.doc));
        let _ = writeln!(s, "typedef struct {} {{", st.short);
        for sl in &st.slots {
            match sl {
                Slot::Field { name, ty, .. } => {
                    let _ = writeln!(s, "    {} {name};", c_base(ty, info));
                }
                Slot::Pad { idx, len } => {
                    let _ = writeln!(s, "    uint8_t _pad{idx}[{len}];");
                }
            }
        }
        let _ = writeln!(s, "}} {};", st.short);
        let _ = writeln!(
            s,
            "_Static_assert(sizeof({}) == {:#x}, \"{} size\");",
            st.short, st.size, st.short
        );
        for sl in &st.slots {
            if let Slot::Field { name, off, .. } = sl {
                let _ = writeln!(
                    s,
                    "_Static_assert(offsetof({}, {name}) == {off:#x}, \"{}.{name} offset\");",
                    st.short, st.short
                );
            }
        }
    }
    if !d.fns.is_empty() || !d.statics.is_empty() || !d.hooks.is_empty() {
        s.push('\n');
    }
    for f in &d.fns {
        match &f.sig {
            Some(sig) => {
                let mut args: Vec<String> =
                    sig.args.iter().map(|(t, n)| c_decl(t, n, info)).collect();
                if sig.varargs {
                    args.push("...".into());
                }
                if args.is_empty() {
                    args.push("void".into());
                }
                let _ = writeln!(s, "/* {} */", c_comment(&f.doc));
                let _ = writeln!(
                    s,
                    "{} dk_fw_{sub}_{}({}) __asm__(\"{}\");",
                    c_ty(&sig.ret, info),
                    f.rust,
                    args.join(", "),
                    f.name
                );
            }
            None => {
                let _ = writeln!(s, "/* {}: no sig yet */", f.name);
            }
        }
    }
    for v in &d.statics {
        let _ = writeln!(s, "/* {} */", c_comment(&v.doc));
        let _ = writeln!(
            s,
            "extern const uint8_t dk_fw_{sub}_{} __asm__(\"{}\");",
            v.rust, v.name
        );
    }
    for h in &d.hooks {
        let args: Vec<String> = h.sig.args.iter().map(|(t, n)| c_decl(t, n, info)).collect();
        if let Some(doc) = &h.doc {
            let _ = writeln!(s, "/* {} */", c_comment(doc));
        }
        let _ = writeln!(
            s,
            "typedef {} dk_fw_{sub}_{}_hook({});",
            c_ty(&h.sig.ret, info),
            h.rust,
            if args.is_empty() {
                "void".to_string()
            } else {
                args.join(", ")
            }
        );
    }
    let _ = writeln!(s, "\n#endif");
    s
}

/// One line of a macro body.
fn gas_ins(s: &mut String, op: &str, operands: &str) {
    let _ = writeln!(s, "    {op:<8}{operands}");
}

/// The register list of a `movem`: `%d0-%d1/%a0-%a1`, a pair as a range.
fn gas_reglist(save: &[&str]) -> String {
    let mut parts = Vec::new();
    for pair in [["d0", "d1"], ["a0", "a1"]] {
        let n = pair.iter().filter(|r| save.contains(*r)).count();
        match n {
            2 => parts.push(format!("%{}-%{}", pair[0], pair[1])),
            1 => parts.push(format!(
                "%{}",
                if save.contains(&pair[0]) {
                    pair[0]
                } else {
                    pair[1]
                }
            )),
            _ => {}
        }
    }
    parts.join("/")
}

/// The macro of a hook: save the registers the stub may not clobber, call the handler with its arguments, restore, continue.
fn gas_hook(sub: &str, h: &HookDef) -> String {
    let mut s = match &h.doc {
        Some(d) => format!("/* {}: {} */\n", h.name, c_comment(d)),
        None => format!("/* {} */\n", h.name),
    };
    let _ = writeln!(s, ".macro dk_fw_{sub}_{}_hook handler, next", h.rust);
    let size = 4 * h.save.len() as u32;
    let list = gas_reglist(&h.save);
    if !h.save.is_empty() {
        gas_ins(&mut s, "lea", &format!("-{size}(%sp),%sp"));
        gas_ins(&mut s, "movem.l", &format!("{list},(%sp)"));
    }
    for (k, a) in h.args.iter().rev().enumerate() {
        match a {
            ArgSrc::Reg(r) => gas_ins(&mut s, "move.l", &format!("%{r},-(%sp)")),
            ArgSrc::Stack(n) => gas_ins(
                &mut s,
                "move.l",
                &format!("{}(%sp),-(%sp)", n + size + 4 * k as u32),
            ),
        }
    }
    gas_ins(&mut s, "jsr", "\\handler");
    let pop = 4 * h.args.len();
    if pop > 8 {
        gas_ins(&mut s, "lea", &format!("{pop}(%sp),%sp"));
    } else if pop > 0 {
        gas_ins(&mut s, "addq.l", &format!("#{pop},%sp"));
    }
    if !h.save.is_empty() {
        gas_ins(&mut s, "movem.l", &format!("(%sp),{list}"));
        gas_ins(&mut s, "lea", &format!("{size}(%sp),%sp"));
    }
    gas_ins(&mut s, "jmp", "\\next");
    s.push_str(".endm\n");
    s
}

fn gas_inc(sub: &str, d: &Sub) -> String {
    let mut s = format!("/* {HEADER} */\n");
    for st in &d.structs {
        let _ = writeln!(s, "/* {}: {} */", st.name, c_comment(&st.doc));
        let _ = writeln!(s, ".equ {}_size, {:#x}", st.short, st.size);
        for sl in &st.slots {
            if let Slot::Field { name, off, .. } = sl {
                let _ = writeln!(s, ".equ {}_{name}, {off:#x}", st.short);
            }
        }
    }
    for h in &d.hooks {
        s.push('\n');
        s.push_str(&gas_hook(sub, h));
    }
    s
}

/// A register name split into its letters and its number: `r10` -> (`r`, 10). None without a plain number.
fn split_reg(r: &str) -> Option<(&str, u32)> {
    let at = r.find(|c: char| c.is_ascii_digit())?;
    let (prefix, num) = r.split_at(at);
    if !num.bytes().all(|b| b.is_ascii_digit()) || (num.len() > 1 && num.starts_with('0')) {
        return None;
    }
    Some((prefix, num.parse().ok()?))
}

fn known_reg(cf: bool, r: &str) -> bool {
    if cf {
        return r == "ccr" || matches!(split_reg(r), Some(("d", 0..=7)) | Some(("a", 0..=6)));
    }
    matches!(r, "astat" | "mode1" | "px")
        || matches!(
            split_reg(r),
            Some(("r" | "i" | "m" | "l" | "b", 0..=15)) | Some(("ustat", 1..=4))
        )
}

/// The register names of a list, with ranges such as `d0-d3` expanded.
fn expand_regs(name: &str, cf: bool, list: &[String]) -> Result<Vec<String>> {
    let mut out = Vec::new();
    for item in list {
        let names: Vec<String> = match item.split_once('-') {
            None => vec![item.clone()],
            Some((a, b)) => match (split_reg(a), split_reg(b)) {
                (Some((pa, na)), Some((pb, nb))) if pa == pb && na <= nb => {
                    (na..=nb).map(|n| format!("{pa}{n}")).collect()
                }
                _ => return Err(err!("{name}: bad register range {item:?}")),
            },
        };
        for n in names {
            if !known_reg(cf, &n) {
                return Err(err!("{name}: unknown register {n:?}"));
            }
            out.push(n);
        }
    }
    Ok(out)
}

/// Checks a hook. A ColdFire hook with a `handler` gives its subsystem and definition.
fn check_hook(
    h: &Hook,
    declared: &BTreeMap<&str, &str>,
    sites: &BTreeMap<&str, &str>,
    info: &Info,
) -> Result<Option<(String, HookDef)>> {
    let name = h.name.as_str();
    let (sub, rust) = split_name(name, "hook")?;
    let cpu = match &h.cpu {
        Some(c) => c.as_str(),
        None if name.starts_with("cf.") => "cf",
        None => "sharc",
    };
    let cf = is_cf(name, cpu)?;
    let site_cpu = declared.get(h.site.as_str()).copied().or_else(|| {
        let (base, n) = h.site.rsplit_once('.')?;
        if n.is_empty() || !n.bytes().all(|b| b.is_ascii_digit()) {
            return None;
        }
        sites.get(base).copied()
    });
    let Some(site_cpu) = site_cpu else {
        return Err(err!(
            "{name}: site {:?} is not a declared fn, site or <sites>.<number>",
            h.site
        ));
    };
    if site_cpu != cpu {
        return Err(err!(
            "{name}: cpu {cpu:?} differs from the cpu {site_cpu:?} of site {}",
            h.site
        ));
    }
    if h.site.split('.').nth(1) != name.split('.').nth(1) {
        return Err(err!(
            "{name}: the subsystem differs from the one of site {}",
            h.site
        ));
    }
    if !matches!(h.mode.as_str(), "before" | "replace" | "retarget") {
        return Err(err!(
            "{name}: mode {:?} is not \"before\", \"replace\" or \"retarget\"",
            h.mode
        ));
    }
    let inputs = expand_regs(name, cf, &h.regs.inputs)?;
    let clobbers = expand_regs(name, cf, &h.regs.clobbers)?;
    if let Some(modes) = &h.regs.modes {
        if cf {
            return Err(err!("{name}: modes are only for a sharc hook"));
        }
        for (k, v) in modes {
            let ok = match split_reg(k) {
                Some(("m" | "l", 0..=15)) => v.is_integer(),
                _ => k == "simd" && v.is_bool(),
            };
            if !ok {
                return Err(err!(
                    "{name}: bad modes entry {k} = {v} (m0-m15, l0-l15: integer; simd: bool)"
                ));
            }
        }
    }
    let Some(handler) = &h.handler else {
        return Ok(None);
    };
    if !cf || !matches!(h.mode.as_str(), "before" | "retarget") {
        return Err(err!(
            "{name}: a handler is only for a cf hook with mode \"before\" or \"retarget\""
        ));
    }
    let sig = parse_sig(name, &handler.sig, info)?;
    if sig.varargs {
        return Err(err!("{name}: the handler sig has varargs"));
    }
    if handler.args.len() != sig.args.len() {
        return Err(err!(
            "{name}: the handler has {} args for a sig with {}",
            handler.args.len(),
            sig.args.len()
        ));
    }
    let mut args = Vec::new();
    for a in &handler.args {
        if let Some(n) = a.strip_prefix("sp+") {
            let off = n
                .bytes()
                .all(|b| b.is_ascii_digit())
                .then(|| n.parse::<u32>().ok())
                .flatten()
                .filter(|o| *o >= 4 && o % 4 == 0)
                .ok_or_else(|| err!("{name}: handler arg {a:?}: expected sp+N with N a multiple of 4, at least 4"))?;
            args.push(ArgSrc::Stack(off));
        } else if known_reg(true, a) && a != "ccr" {
            if !inputs.contains(a) {
                return Err(err!("{name}: handler arg {a} is not in regs.in"));
            }
            args.push(ArgSrc::Reg(a.clone()));
        } else {
            return Err(err!("{name}: handler arg {a:?} is not a register or sp+N"));
        }
    }
    let save = ["d0", "d1", "a0", "a1"]
        .into_iter()
        .filter(|r| !clobbers.iter().any(|c| c == r))
        .collect();
    Ok(Some((
        sub,
        HookDef {
            name: h.name.clone(),
            rust,
            doc: h.doc.clone(),
            sig,
            save,
            args,
        },
    )))
}

/// The outputs from declaration files given as (path relative to the repository root, text).
pub fn render(decls: &[(&str, &str)]) -> Result<Vec<(String, String)>> {
    let mut files = Vec::new();
    for (path, text) in decls {
        let f: Files = toml::from_str(text).map_err(|e| err!("{path}: {e}"))?;
        files.push(f);
    }
    // every entry needs a doc
    for f in &files {
        let docs = f
            .r#fn
            .iter()
            .chain(&f.site)
            .chain(&f.data)
            .chain(&f.value)
            .chain(&f.sites)
            .map(|e| (&e.name, &e.doc))
            .chain(f.r#struct.iter().map(|s| (&s.name, &s.doc)))
            .chain(f.hook.iter().map(|h| (&h.name, &h.doc)));
        for (name, doc) in docs {
            if doc.as_deref().is_none_or(|d| d.trim().is_empty()) {
                return Err(err!("{name}: no doc"));
            }
        }
    }
    // the structs first: their short names and sizes are the types of the other entries
    let mut info = Info::new();
    for f in &files {
        for s in &f.r#struct {
            let cf = match &s.cpu {
                Some(c) => is_cf(&s.name, c)?,
                None => s.name.starts_with("cf."),
            };
            if !cf {
                continue;
            }
            let (sub, short) = split_name(&s.name, "struct")?;
            let short = s.name.rsplit('.').next().unwrap_or(&short).to_string();
            if info.insert(short.clone(), (sub, s.size)).is_some() {
                return Err(err!("{}: struct name {short} twice", s.name));
            }
        }
    }
    let mut subs: BTreeMap<String, Sub> = BTreeMap::new();
    for f in &files {
        for s in &f.r#struct {
            let short = s.name.rsplit('.').next().unwrap_or(&s.name).to_string();
            match info.get(&short) {
                Some((sub, _)) if s.name.split('.').nth(1) == Some(sub.as_str()) => {
                    let slots = layout(s, &info)?;
                    subs.entry(sub.clone())
                        .or_default()
                        .structs
                        .push(StructDef {
                            name: s.name.clone(),
                            short,
                            size: s.size,
                            slots,
                            doc: s.doc.clone().unwrap_or_default(),
                        });
                }
                _ => {}
            }
        }
        for (kind, list) in [
            ("fn", &f.r#fn),
            ("data", &f.data),
            ("value", &f.value),
            ("site", &f.site),
            ("sites", &f.sites),
        ] {
            for e in list {
                if !is_cf(&e.name, &e.cpu)? {
                    continue;
                }
                let (sub, rust) = split_name(&e.name, kind)?;
                let bound = match e.bind.as_deref() {
                    None => false,
                    Some("static") if kind == "site" => true,
                    Some(b) => {
                        return Err(err!(
                            "{}: bind {b:?} is not allowed (only \"static\", on a site)",
                            e.name
                        ));
                    }
                };
                let d = subs.entry(sub).or_default();
                match kind {
                    "fn" => {
                        let sig = match &e.sig {
                            Some(t) => Some(parse_sig(&e.name, t, &info)?),
                            None => None,
                        };
                        d.fns.push(FnDef {
                            name: e.name.clone(),
                            rust,
                            sig,
                            doc: e.doc.clone().unwrap_or_default(),
                        });
                    }
                    "data" | "value" => d.statics.push(StaticDef {
                        name: e.name.clone(),
                        rust,
                        doc: e.doc.clone().unwrap_or_default(),
                    }),
                    "site" if bound => d.statics.push(StaticDef {
                        name: e.name.clone(),
                        rust,
                        doc: e.doc.clone().unwrap_or_default(),
                    }),
                    _ => {}
                }
            }
        }
    }
    // the hooks check their `site` against every declared fn, site and sites entry
    let mut declared: BTreeMap<&str, &str> = BTreeMap::new();
    let mut sites: BTreeMap<&str, &str> = BTreeMap::new();
    for f in &files {
        for e in f.r#fn.iter().chain(&f.site) {
            declared.insert(&e.name, &e.cpu);
        }
        for e in &f.sites {
            sites.insert(&e.name, &e.cpu);
        }
    }
    for f in &files {
        for h in &f.hook {
            if let Some((sub, def)) = check_hook(h, &declared, &sites, &info)? {
                subs.entry(sub).or_default().hooks.push(def);
            }
        }
    }
    // a subsystem with only sites has no output
    subs.retain(|_, d| {
        !d.structs.is_empty() || !d.fns.is_empty() || !d.statics.is_empty() || !d.hooks.is_empty()
    });
    for (sub, d) in subs.iter_mut() {
        d.hooks.sort_by(|a, b| a.name.cmp(&b.name));
        d.structs.sort_by(|a, b| a.name.cmp(&b.name));
        d.fns.sort_by(|a, b| a.name.cmp(&b.name));
        d.statics.sort_by(|a, b| a.name.cmp(&b.name));
        let structs = std::mem::take(&mut d.structs);
        d.structs = order(sub, structs, &info)?;
        let mut seen: Vec<&str> = Vec::new();
        for r in d
            .fns
            .iter()
            .map(|f| f.rust.as_str())
            .chain(d.statics.iter().map(|v| v.rust.as_str()))
        {
            if seen.contains(&r) {
                return Err(err!("{sub}: the binding name {r} is used twice"));
            }
            seen.push(r);
        }
    }
    let mut out = vec![(RUST_OUT.to_string(), rust(&subs, &info))];
    for (sub, d) in &subs {
        out.push((
            format!("{OUT_DIR}/include/dk_fw_{sub}.h"),
            c_header(sub, d, &info),
        ));
        if !d.structs.is_empty() || !d.hooks.is_empty() {
            out.push((format!("{OUT_DIR}/inc/dk_fw_{sub}.inc"), gas_inc(sub, d)));
        }
    }
    Ok(out)
}

/// The `.toml` files under `dir` (not `subsystems.toml` at the top), as (path relative to the root, text) in path order.
fn collect(root: &Path, dir: &Path, rel: &str, out: &mut Vec<(String, String)>) -> Result<()> {
    let mut paths: Vec<_> = std::fs::read_dir(dir)
        .map_err(|e| err!("{}: {e}", dir.display()))?
        .map(|e| e.map(|e| e.path()))
        .collect::<std::io::Result<_>>()
        .map_err(|e| err!("{}: {e}", dir.display()))?;
    paths.sort();
    for p in paths {
        let name = p
            .file_name()
            .unwrap_or_default()
            .to_string_lossy()
            .to_string();
        let r = format!("{rel}/{name}");
        if p.is_dir() {
            collect(root, &p, &r, out)?;
        } else if name.ends_with(".toml") && r != format!("{SOURCE}/subsystems.toml") {
            let text = std::fs::read_to_string(&p).map_err(|e| err!("{}: {e}", p.display()))?;
            out.push((r, text));
        }
    }
    Ok(())
}

/// The outputs, reading `devices/fw/` under the repository root.
pub fn generate(root: &Path) -> Result<Vec<(String, String)>> {
    let mut files = Vec::new();
    collect(root, &root.join(SOURCE), SOURCE, &mut files)?;
    let refs: Vec<(&str, &str)> = files
        .iter()
        .map(|(p, t)| (p.as_str(), t.as_str()))
        .collect();
    render(&refs)
}

