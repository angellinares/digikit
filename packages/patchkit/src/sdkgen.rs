fn parse(text: &str) -> Result<Sdk> {
    let sdk: Sdk = toml::from_str(text).map_err(|e| err!("{SOURCE}: {e}"))?;
    let mut last = 0;
    for k in &sdk.log.kind {
        if k.id <= last {
            return Err(err!(
                "{SOURCE}: kind {} ({}) is not in ascending order",
                k.id,
                k.name
            ));
        }
        last = k.id;
        if k.args.len() != 5 {
            return Err(err!("{SOURCE}: kind {} ({}) needs 5 args", k.id, k.name));
        }
    }
    for (i, k) in sdk.log.kind.iter().enumerate() {
        if sdk.log.kind[..i].iter().any(|o| o.name == k.name) {
            return Err(err!("{SOURCE}: kind name {} twice", k.name));
        }
    }
    runtime_parts(&sdk)?;
    guards(&sdk)?;
    let p = &sdk.protocol;
    for (i, (n, v)) in p.commands.iter().enumerate() {
        if p.commands.iter().skip(i + 1).any(|(_, w)| w == v) {
            return Err(err!(
                "{SOURCE}: protocol command number {v:#04x} ({n}) twice"
            ));
        }
    }
    for (i, (n, [first, last])) in p.ranges.iter().enumerate() {
        if *first == 0 || first > last || *last > 0x3f {
            return Err(err!(
                "{SOURCE}: protocol range {n}: [{first:#04x}, {last:#04x}] is not inside 0x01..=0x3f"
            ));
        }
        let hit = |v: u8| v >= *first && v <= *last;
        if let Some((c, _)) = p.commands.iter().find(|(_, v)| hit(**v)) {
            return Err(err!("{SOURCE}: protocol range {n} holds the command {c}"));
        }
        if let Some((o, _)) = p
            .ranges
            .iter()
            .skip(i + 1)
            .find(|(_, [f, l])| f <= last && first <= l)
        {
            return Err(err!("{SOURCE}: protocol ranges {n} and {o} overlap"));
        }
    }
    for (i, (n, v)) in p.service.iter().enumerate() {
        if !p.ranges.values().any(|[f, l]| v >= f && v <= l) {
            return Err(err!(
                "{SOURCE}: protocol service command {n} ({v:#04x}) is in no range of [protocol.ranges]"
            ));
        }
        if p.service.iter().skip(i + 1).any(|(_, w)| w == v) {
            return Err(err!(
                "{SOURCE}: protocol service command number {v:#04x} ({n}) twice"
            ));
        }
    }
    for (i, (n, v)) in p.caps.iter().enumerate() {
        if *v > 31 {
            return Err(err!("{SOURCE}: protocol cap {n}: bit {v} is not below 32"));
        }
        if p.caps.iter().skip(i + 1).any(|(_, w)| w == v) {
            return Err(err!("{SOURCE}: protocol cap bit {v} ({n}) twice"));
        }
    }
    for (i, (n, v)) in sdk.capacity.kinds.iter().enumerate() {
        if *v == 0 || sdk.capacity.kinds.iter().skip(i + 1).any(|(_, w)| w == v) {
            return Err(err!("{SOURCE}: capacity kind {v} ({n}) is 0 or twice"));
        }
    }
    let st = &sdk.settings;
    if st.copies != 2 || st.sectors == 0 || st.key_max == 0 || st.key_max > 255 || st.value_max == 0
    {
        return Err(err!(
            "{SOURCE}: [settings] needs 2 copies, a size, a key limit of 1 to 255 and a value limit"
        ));
    }
    // a record holds its header (18 bytes), one entry of the longest key and the longest value must fit in a copy
    if u64::from(st.sectors) * 512 < 18 + 3 + u64::from(st.key_max) + u64::from(st.value_max) {
        return Err(err!(
            "{SOURCE}: [settings] a copy is too small for one entry of the longest key and value"
        ));
    }
    for (i, k) in st.key.iter().enumerate() {
        if !["u8", "route", "u8x16"].contains(&k.value.as_str()) {
            return Err(err!(
                "{SOURCE}: [[settings.key]] {}: unknown value kind {}",
                k.prefix,
                k.value
            ));
        }
        if k.prefix.is_empty()
            || !k.prefix.ends_with('/')
            || st.key[..i].iter().any(|o| o.prefix == k.prefix)
        {
            return Err(err!(
                "{SOURCE}: [[settings.key]] prefix {:?} is empty, does not end in / or is twice",
                k.prefix
            ));
        }
    }
    for (what, table) in [("protocol", &p.status), ("load", &sdk.load.status)] {
        for (i, (n, s)) in table.iter().enumerate() {
            if s.code >= 0 || (what == "protocol" && s.code < -128) {
                return Err(err!(
                    "{SOURCE}: {what} status {n}: code {} out of range",
                    s.code
                ));
            }
            if table.iter().skip(i + 1).any(|(_, t)| t.code == s.code) {
                return Err(err!("{SOURCE}: {what} status code {} ({n}) twice", s.code));
            }
        }
    }
    check_views(&sdk)?;
    Ok(sdk)
}

/// The statuses in the order of their codes, from -1 down.
fn by_code(t: &BTreeMap<String, Status>) -> Vec<(&String, &Status)> {
    let mut v: Vec<_> = t.iter().collect();
    v.sort_by_key(|(_, s)| -s.code);
    v
}

/// The (name, value) pairs of a table in value order.
fn by_value<T: Ord + Copy>(t: &BTreeMap<String, T>) -> Vec<(&String, T)> {
    let mut v: Vec<_> = t.iter().map(|(n, x)| (n, *x)).collect();
    v.sort_by_key(|(_, x)| *x);
    v
}

/// The protocol's Rust constants, one per line with `indent`; the statuses have type `status_ty`.
fn proto_consts(sdk: &Sdk, indent: &str, status_ty: &str) -> String {
    let p = &sdk.protocol;
    let mut s = String::new();
    let _ = writeln!(s, "{indent}pub const VERSION: u8 = {};", p.version);
    for (n, v) in p.limits.all() {
        let _ = writeln!(s, "{indent}pub const {n}: usize = {v};");
    }
    for (n, v) in by_value(&p.commands) {
        let _ = writeln!(s, "{indent}pub const CMD_{n}: u8 = {v:#04x};");
    }
    for (n, v) in by_value(&p.service) {
        let _ = writeln!(s, "{indent}pub const SVC_{n}: u8 = {v:#04x};");
    }
    for (n, st) in by_code(&p.status) {
        let _ = writeln!(s, "{indent}pub const {n}: {status_ty} = {};", st.code);
    }
    for (n, bit) in by_value(&p.caps) {
        let _ = writeln!(s, "{indent}pub const CAP_{n}: u32 = 1 << {bit};");
    }
    for (n, k) in by_value(&sdk.capacity.kinds) {
        let _ = writeln!(s, "{indent}pub const CAPK_{n}: u8 = {k};");
    }
    let _ = writeln!(
        s,
        "{indent}/// The command ranges a module may register, as (first, last)."
    );
    let _ = writeln!(
        s,
        "{indent}pub const RANGES: [(u8, u8); {}] = [",
        p.ranges.len()
    );
    for (n, [first, last]) in &p.ranges {
        let _ = writeln!(
            s,
            "{indent}    ({first:#04x}, {last:#04x}), // {n}"
        );
    }
    let _ = writeln!(s, "{indent}];");
    for (n, [first, last]) in &p.ranges {
        let _ = writeln!(
            s,
            "{indent}pub const RANGE_{}: (u8, u8) = ({first:#04x}, {last:#04x});",
            n.to_uppercase()
        );
    }
    s
}

fn guards(sdk: &Sdk) -> Result<Vec<(u32, &str)>> {
    let mut v = Vec::new();
    for (k, name) in &sdk.log.guard_kinds {
        let id: u32 = k
            .parse()
            .map_err(|_| err!("{SOURCE}: guard_kinds key {k} is not a number"))?;
        v.push((id, name.as_str()));
    }
    v.sort();
    Ok(v)
}

fn rust(sdk: &Sdk) -> String {
    let mut s = format!("// {HEADER}\n\n");
    let rv = runtime_parts(sdk).expect("parse checked the runtime version");
    let _ = writeln!(s, "// {}.{}.{}", rv.0, rv.1, rv.2);
    let _ = writeln!(
        s,
        "pub const RUNTIME_VERSION: u32 = {:#08x};\n",
        pack_runtime(rv)
    );
    let c = &sdk.contract;
    s.push_str("pub mod contract {\n");
    for (n, v) in [
        ("API", c.api),
        ("MACHINE", c.machine),
        ("FX", c.fx),
        ("SERVICE", c.service),
    ] {
        let _ = writeln!(s, "    pub const {n}: (u8, u8) = ({}, {});", v[0], v[1]);
    }
    s.push_str("}\n\npub mod logk {\n");
    for k in &sdk.log.kind {
        let _ = writeln!(s, "    pub const {}: u16 = {};", k.name, k.id);
    }
    let mut consts: Vec<(&String, &u32)> = sdk.log.consts.iter().collect();
    consts.sort_by_key(|(n, v)| (**v, (*n).clone()));
    for (n, v) in consts {
        let _ = writeln!(s, "    pub const {n}: u32 = {v};");
    }
    let l = &sdk.log;
    for (n, v) in [
        ("F_ERROR", l.f_error),
        ("LEVEL_SHIFT", l.level_shift),
        ("LEVEL_MASK", l.level_mask),
        ("SOURCE_SHIFT", l.source_shift),
        ("SOURCE_MASK", l.source_mask),
    ] {
        let _ = writeln!(s, "    pub const {n}: u16 = {v};");
    }
    for (i, n) in LEVELS.iter().enumerate() {
        let _ = writeln!(s, "    pub const L_{}: u16 = {i};", n.to_uppercase());
    }
    s.push_str("}\n\n/// Format and table limits (`[limits.max]` and `DK_PAGE_KNOBS`): array sizes of the runtime.\npub mod limits {\n");
    let m = &sdk.limits.max;
    let _ = writeln!(s, "    pub const SEL_MAX: usize = {};", m.modules);
    let _ = writeln!(s, "    pub const MAP_N: usize = {};", m.map_entries);
    let _ = writeln!(s, "    pub const MACHINE_ROWS: usize = {};", m.machine_rows);
    let _ = writeln!(s, "    pub const PARAM_ROWS: usize = {};", m.param_rows);
    let _ = writeln!(s, "    pub const PAGE_ROWS: usize = {};", m.page_rows);
    let _ = writeln!(s, "    pub const STAGE_BYTES: usize = {};", m.stage_bytes);
    let _ = writeln!(
        s,
        "    pub const PAGE_KNOBS: usize = {};",
        page_knobs_of(sdk)
    );
    s.push_str("}\n\n");
    s.push_str(&rust_settings(sdk));
    s.push_str("\npub mod proto {\n");
    s.push_str(&proto_consts(sdk, "    ", "i32"));
    s.push_str("}\n\npub mod load {\n");
    for (n, st) in by_code(&sdk.load.status) {
        let _ = writeln!(s, "    pub const {n}: i32 = {};", st.code);
    }
    s.push_str("}\n");
    s
}

/// The settings record's constants (`[settings]`), for `gen_sdk.rs`.
fn rust_settings(sdk: &Sdk) -> String {
    let st = &sdk.settings;
    let mut s = String::from(
        "/// The settings record (`[settings]`): the area of one copy, the key and value limits and the keys by owner.\npub mod settings {\n",
    );
    let _ = writeln!(s, "    pub const SECTORS: u32 = {};", st.sectors);
    let _ = writeln!(s, "    pub const COPIES: u32 = {};", st.copies);
    let _ = writeln!(s, "    pub const KEY_MAX: usize = {};", st.key_max);
    let _ = writeln!(s, "    pub const VALUE_MAX: usize = {};", st.value_max);
    s.push_str("    /// (prefix, how a host reader decodes the value)\n");
    let _ = writeln!(
        s,
        "    pub const KEYS: [(&str, &str); {}] = [",
        st.key.len()
    );
    for k in &st.key {
        let _ = writeln!(s, "        ({:?}, {:?}),", k.prefix, k.value);
    }
    s.push_str("    ];\n}\n");
    s
}

/// One `code: (name, text),` line of a Python status table (expanded when it is wider than `PY_WIDTH`).
fn py_status(s: &mut String, name: &str, st: &Status) {
    let one = format!("    {}: ({name:?}, {:?}),", st.code, st.text);
    if one.chars().count() <= PY_WIDTH {
        s.push_str(&one);
        s.push('\n');
    } else {
        let _ = writeln!(
            s,
            "    {}: (\n        {name:?},\n        {:?},\n    ),",
            st.code, st.text
        );
    }
}

/// `tools/device/dkproto.py`: the protocol numbers and the status texts.
