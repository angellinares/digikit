/// The value of a `[format] consts` entry (the header offsets), 0 if it is missing.
fn header_const(sdk: &Sdk, name: &str) -> u32 {
    sdk.format
        .consts
        .iter()
        .find(|c| c.name == name)
        .map_or(0, |c| c.value)
}
