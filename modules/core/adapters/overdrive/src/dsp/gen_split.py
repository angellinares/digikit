"""Writes split.inc, the frame split of src/dsp/overdrive.s unrolled over the 16 tracks (no index register, so no L register
to depend on at the hook site), and consts.inc / k.inc, the curve constants: their indexes and the words of `_od_k`.

    uv run python modules/core/adapters/overdrive/src/dsp/gen_split.py
"""

import math
import struct
from pathlib import Path

# The DSP addresses its frame copy in bytes, two per halfword (core/dsp-voice `_dv_frame_hw`): track t's OVR TYPE, halfword
# 0x9c + 48 t, is the low half of the 32-bit word at byte 0x138 + 0x60 t.
ROUTING = 0x138
lines = ["// Generated by gen_split.py; do not edit."]
for t in range(16):
    w = ROUTING + 0x60 * t
    lines += [
        f"    R0 = DM(_fw_frame + {w:#x});",
        "    R1 = FEXT R0 BY 9:7;",
        f"    DM(_od_flav + {4 * t}) = R1;",
        "    R1 = 0xffff01ff;",
        "    R0 = R0 AND R1;",
        f"    DM(_fw_frame + {w:#x}) = R0;",
    ]
Path(__file__).with_name("split.inc").write_text("\n".join(lines) + "\n")

# the constants of `_od_k`, read through I4 at K_<name>
K = [
    ("ONE", 1.0),
    ("M1", -1.0),
    ("EIGHT", 8.0),  # the stock curve's small-signal gain: z = 8 drive x
    ("FOUR", 4.0),
    ("TWO", 2.0),
    ("HALF", 0.5),
    ("QUARTER", 0.25),
    ("K64", 64.0),
    ("SQR", 64.0),
    ("FUZZB", 0.3),
    ("FUZZLO", -0.6),
    ("TUBEB", 0.4),
    ("TUBEO", math.tanh(0.4)),
    ("TCLAMP", 4.97),
    ("P0", 135135.0),
    ("P1", 17325.0),
    ("P2", 378.0),
    ("P3", 1.0),
    ("Q1", 62370.0),
    ("Q2", 3150.0),
    ("Q3", 28.0),
]
words = struct.unpack(f"<{len(K)}I", struct.pack(f"<{len(K)}f", *[v for _, v in K]))
Path(__file__).with_name("consts.inc").write_text(
    "// Generated by gen_split.py; do not edit.\n"
    + "".join(f"#define K_{n} {i}\n" for i, (n, _) in enumerate(K))
)
Path(__file__).with_name("k.inc").write_text(
    "// Generated by gen_split.py; do not edit.\n"
    + "".join(
        f".VAR _od_k{i or ''} = {w:#010x};   // {n} {v!r}\n"
        for i, ((n, v), w) in enumerate(zip(K, words, strict=True))
    )
)
