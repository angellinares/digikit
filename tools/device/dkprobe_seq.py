"""The probe sequence: the RECIPS and RSQRTS inputs that the SHARC probe module runs, in order, and the framing of its words.

One source for both sides. `write_inc` writes the table the DSP module includes (`probe_seq.inc`); `tools/device/dkprobe.py` expands the same
lists to put the input next to each captured result. The module sends the table's checksum in its run header, so a module built from another
table is detected.

The stream (one 32-bit word per block, through diagnostic word 25 of the DSP reply):

  frame   = header, 3 * RECORDS_PER_FRAME payload words, checksum
  header  = 0xB0 << 24 | payload word count << 16 | frame number (16 bits, counts up across runs)
  checksum= s1 ^ s2 over header and payload, with s1 += w; s2 += s1 per word (32-bit, start 0)
  record  = 3 words. A run is R records, a multiple of RECORDS_PER_FRAME:
              record 0     run counter, number of items, table checksum (same s1 ^ s2 over the table words)
              record 1     MODE1, ASTAT, STKY as the module found them
              record 2..   one per item: result bits, ASTAT after, STKY after (both cleared before the item: ASTAT bits 0-13, STKY all)
              padding      0xFFFFFFFF x 3
"""

from __future__ import annotations

from pathlib import Path

RECORDS_PER_FRAME = 4
WORDS_PER_RECORD = 3
PAYLOAD_WORDS = RECORDS_PER_FRAME * WORDS_PER_RECORD
FRAME_WORDS = PAYLOAD_WORDS + 2
HDR_MAGIC = 0xB0
PAD = 0xFFFFFFFF

KIND = "sharc-recips"
OP_RECIPS = "recips"
OP_RSQRTS = "rsqrts"

# lower 16 bits of the mantissa (the 7 bits above them are the table index)
LOW_RECIPS = (0x0000, 0xFFFF, 0xAAAA)
LOW_RSQRTS = (0x0000, 0xFFFF)
EXP_RECIPS = (1, 126, 127, 128, 253, 254)
EXP_RSQRTS = (1, 2, 126, 127, 128, 129, 253, 254)
# a few negative inputs for RSQRTS (index, exponent)
NEG_RSQRTS_IDX = (0, 64, 127)
NEG_RSQRTS_EXP = (127, 128)

SPECIALS = (
    0x00000000,  # +0
    0x80000000,  # -0
    0x7F800000,  # +inf
    0xFF800000,  # -inf
    0x7FC00000,  # quiet NaN
    0xFFC00000,  # negative quiet NaN
    0x7F800001,  # signalling NaN
    0x7FFFFFFF,  # NaN, all mantissa ones
    0x00800000,  # smallest normal
    0x80800000,  # its negative
    0x00000001,  # smallest denormal
    0x80000001,
    0x007FFFFF,  # largest denormal
    0x807FFFFF,
    0x7F7FFFFF,  # largest normal
    0xFF7FFFFF,
)


def _bits(sign: int, exp: int, idx: int, low: int) -> int:
    return (sign << 31) | (exp << 23) | (idx << 16) | low


def items() -> list[tuple[str, int]]:
    """The items in the order the module runs them: (op, input bits)."""
    out: list[tuple[str, int]] = []
    for exp in EXP_RECIPS:
        for sign in (0, 1):
            for low in LOW_RECIPS:
                for idx in range(128):
                    out.append((OP_RECIPS, _bits(sign, exp, idx, low)))
    out += [(OP_RECIPS, v) for v in SPECIALS]
    for exp in EXP_RSQRTS:
        for low in LOW_RSQRTS:
            for idx in range(128):
                out.append((OP_RSQRTS, _bits(0, exp, idx, low)))
    for exp in NEG_RSQRTS_EXP:
        for idx in NEG_RSQRTS_IDX:
            out.append((OP_RSQRTS, _bits(1, exp, idx, 0)))
    out += [(OP_RSQRTS, v) for v in SPECIALS]
    return out


def n_recips() -> int:
    return sum(1 for op, _ in items() if op == OP_RECIPS)


def fletcher(words: list[int]) -> int:
    """s1 ^ s2 with s1 += w, s2 += s1 (32-bit), the checksum of a frame and of the table."""
    s1 = s2 = 0
    for w in words:
        s1 = (s1 + w) & 0xFFFFFFFF
        s2 = (s2 + s1) & 0xFFFFFFFF
    return s1 ^ s2


def table_words() -> list[int]:
    return [v for _, v in items()]


def table_checksum() -> int:
    return fletcher(table_words())


def records_per_run() -> int:
    n = 2 + len(items())
    return -(-n // RECORDS_PER_FRAME) * RECORDS_PER_FRAME


def frames_per_run() -> int:
    return records_per_run() // RECORDS_PER_FRAME


def words_per_run() -> int:
    return frames_per_run() * FRAME_WORDS


def header_word(seq: int) -> int:
    return (HDR_MAGIC << 24) | (PAYLOAD_WORDS << 16) | (seq & 0xFFFF)


def inc_text() -> str:
    """The assembler include: the constants and the input table."""
    its = items()
    assert len(its) % 2 == 0, "the DSP checksum loop takes two table words per pass"
    lines = [
        "// Generated by tools/device/dkprobe_seq.py (`uv run python -m tools.device.dkprobe_seq --write PATH`). Do not edit.",
        "// The inputs of the probe sequence (RECIPS items first, then RSQRTS) and the sizes the routine needs.",
        f"#define PR_NITEMS {len(its)}",
        f"#define PR_NRECIP {n_recips()}",
        f"#define PR_NRECORDS {records_per_run()}",
        f"#define PR_TAB_BYTES {4 * len(its)}",
        "",
        ".SECTION/DM seg_dmda;",
        ".GLOBAL _pr_tab;",
    ]
    # One `.VAR` per word: the assembler turns an initialiser list into relocations that the object reader refuses. The names follow in memory order.
    for i, v in enumerate(table_words()):
        lines.append(f".VAR _pr_tab{'' if i == 0 else i} = 0x{v:08x};")
    return "\n".join(lines) + "\n"


def write_inc(path: Path) -> None:
    path.write_text(inc_text())


def main(argv: list[str] | None = None) -> int:
    import argparse

    ap = argparse.ArgumentParser(
        description="Write the probe sequence include for the DSP module"
    )
    ap.add_argument("--write", type=Path, required=True, help="the .inc file to write")
    args = ap.parse_args(argv)
    write_inc(args.write)
    print(
        f"{len(items())} items ({n_recips()} RECIPS), {records_per_run()} records, "
        f"{words_per_run()} words per run, table checksum 0x{table_checksum():08x}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
